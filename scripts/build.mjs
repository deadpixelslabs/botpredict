import { build } from 'esbuild';
import { copyFile, mkdir, rm } from 'node:fs/promises';
await mkdir('public', { recursive: true });
await copyFile('public/dashboard.html', 'public/index.html');
await mkdir('public/vendor', { recursive: true });
await copyFile('node_modules/chart.js/dist/chart.umd.js', 'public/vendor/chart.umd.js');
await mkdir('api', { recursive: true });
await build({ entryPoints: ['server/vercelEntry.ts'], outfile: 'api/handler.js', bundle: true,
  platform: 'node', target: 'node22', format: 'esm', packages: 'external', sourcemap: false,
  banner: { js: '// Generated by npm run build from server/vercelEntry.ts. Commit this deployable Function.' },
  logLevel: 'info' });
await rm('dist/api.cjs', { force: true });
await import('./build-worker.mjs');
